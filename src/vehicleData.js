export const getVehicleImageKey = (vehicle) => {
  const manufacturer = vehicle.manufacturer
    .trim()
    .toUpperCase()
    .replace(/\s+/g, "-")
    .replace(/[^A-Z0-9-]/g, "");

  const model = vehicle.model
    .trim()
    .toUpperCase()
    .replace(/\s+/g, "-")
    .replace(/[^A-Z0-9-]/g, "");

  return `${manufacturer}-${model}`;
};

